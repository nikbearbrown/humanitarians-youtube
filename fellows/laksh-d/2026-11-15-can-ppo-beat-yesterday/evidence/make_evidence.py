"""Compute every number and curve the video shows, from lakshdhamija/rl-autoscaler @ 35e922d.

Run inside the rl-autoscaler venv (Python 3.11, package rl_autoscaler installed):
    cd ~/code/rl-autoscaler && source .venv/bin/activate
    python <reel>/evidence/make_evidence.py
Writes evidence.json next to this file, then embeds it into ../scenes.py between the
EVIDENCE markers (scenes.py must be self-contained: the QC gates copy it to a temp dir).
Reads the repo's processed data and results/ppo/*.json; writes nothing inside the repo.
"""

import json
import re
import subprocess
from collections import defaultdict
from pathlib import Path

import numpy as np

from rl_autoscaler.data import load
from rl_autoscaler.policies import SeasonalPolicy, ThresholdPolicy
from rl_autoscaler.train import score

HERE = Path(__file__).resolve().parent
REPO = Path.home() / "code" / "rl-autoscaler"
commit = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
TARGETS = (0.4, 0.5, 0.6, 0.7, 0.8)

# baselines on the 5 held-out apps (13 test days each), at several target utilizations
base = {name: [score(lambda: policy(target=t), "test_apps") for t in TARGETS]
        for name, policy in (("kubernetes", ThresholdPolicy), ("yesterday", SeasonalPolicy))}
curves = {name: [[round(p["cost_per_day"]), round(p["late_pct"], 2)] for p in pts] for name, pts in base.items()}

# the 30 PPO runs: mean over 3 seeds per late penalty, plus the seed range of late %
runs = defaultdict(lambda: defaultdict(list))
for path in sorted((REPO / "results" / "ppo").glob("*.json")):
    r = json.loads(path.read_text())
    runs[r["kind"]][r["penalty"]].append(r)
ppo, steps = {}, {}
for kind, by_pen in runs.items():
    ppo[kind] = []
    for pen in sorted(by_pen):
        cost = [x["test_apps"]["cost_per_day"] for x in by_pen[pen]]
        late = [x["test_apps"]["late_pct"] for x in by_pen[pen]]
        ppo[kind].append({"penalty": pen, "cost": round(float(np.mean(cost))), "late": round(float(np.mean(late)), 2),
                          "late_min": round(min(late), 2), "late_max": round(max(late), 2), "seeds": len(late)})
    steps[kind] = by_pen[sorted(by_pen)[0]][0]["steps"]
n_runs = sum(len(v) for by_pen in runs.values() for v in by_pen.values())
assert n_runs == 30 and all(p["seeds"] == 3 for k in ppo for p in ppo[k])
best = ppo["residual"][-1]   # highest penalty
rule60 = curves["yesterday"][TARGETS.index(0.6)]

# weekly shape: each app's daily total divided by its own 14-day mean, then the median over the 19 apps
apps, _ = load()
daily = np.array([s.reshape(14, 1440).sum(1) / s.reshape(14, 1440).sum(1).mean() for s in apps.values()])
weekly = [round(float(v), 3) for v in np.median(daily, axis=0)]
quiet = sorted(int(i) + 1 for i in np.argsort(weekly)[:4])
busiest = int(np.argmax(weekly)) + 1
assert quiet == [6, 7, 13, 14] and busiest == 8

pytest_out = (HERE / "pytest_stdout.txt").read_text()
n_tests = int(re.search(r"(\d+) passed", pytest_out).group(1))

evidence = {
    "source": f"lakshdhamija/rl-autoscaler @ {commit}; Azure Functions Trace 2019 (Shahrad et al., USENIX ATC 2020), CC-BY 4.0",
    "targets": TARGETS, "curves": curves, "ppo": ppo, "steps": steps, "n_runs": n_runs,
    "best": best, "rule60": rule60, "weekly": weekly, "quiet": quiet, "busiest": busiest, "n_tests": n_tests,
}
(HERE / "evidence.json").write_text(json.dumps(evidence, indent=1))

scenes = HERE.parent / "scenes.py"
if scenes.exists():
    block = "# >>> EVIDENCE (generated by evidence/make_evidence.py; do not edit)\nEVIDENCE = json.loads(r'''" + \
            json.dumps(evidence, separators=(",", ":")) + "''')\n# <<< EVIDENCE"
    scenes.write_text(re.sub(r"# >>> EVIDENCE.*?# <<< EVIDENCE", lambda _: block, scenes.read_text(), flags=re.S))
print(json.dumps({k: evidence[k] for k in ("source", "curves", "best", "rule60", "weekly", "quiet", "busiest", "n_runs", "steps", "n_tests")}))
