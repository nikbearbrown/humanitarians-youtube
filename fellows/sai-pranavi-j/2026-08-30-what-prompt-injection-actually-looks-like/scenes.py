# B00 — TITLE: silent opening card, video title + @HumanitariansAI, no VO.
# Same bracket idiom as this fellow's sibling reels' B00_TitleCard: top/bottom
# gold rules (not a single underline) so a title-only/handle-only card still
# earns real canvas-fill (GATE V's 55% floor) from spacing, not word count.
# Audio: mp3/beat-B00.mp3 is a REAL silent mp3 (ffmpeg anullsrc, 4.05s
# measured), never audio_file: null — see beat_sheet.json's B00 shot.note.
