class B00_TitleCard(Scene):
    def construct(self):
        self.camera.background_color = PALETTE["bg"]

        title_line1 = fit(Text("Prompt Injection:", color=PALETTE["ink"], font_size=64, weight="BOLD"), 11.5)
        title_line2 = fit(Text("The Vulnerability", color=PALETTE["ink"], font_size=64, weight="BOLD"), 11.5)
        title_line3 = fit(Text("Hiding in Plain Text", color=PALETTE["ink"], font_size=64, weight="BOLD"), 11.5)
        title = VGroup(title_line1, title_line2, title_line3).arrange(DOWN, buff=0.26)

        # rule span widened 3.0->4.4 each side (8.8 total, ~70% of the 12.6
        # safe width) — canvas-fill is a bbox AREA ratio (width x height),
        # so a narrow-but-tall centered text stack underfills on the WIDTH
        # axis even with generous vertical buff; real measurement (2nd GATE
        # V pass) confirmed a wide decorative rule is the fix, not more
        # vertical spacing (which only pushed the height axis, not width).
        top_rule = Line(LEFT * 4.4, RIGHT * 4.4, color=PALETTE["gold"], stroke_width=3)
        bottom_rule = Line(LEFT * 4.4, RIGHT * 4.4, color=PALETTE["gold"], stroke_width=3)
        handle = Text("@HumanitariansAI", color=PALETTE["slate"], font_size=44)

        # buff 1.4 -> 1.2 — with the wider rules above already carrying the
        # width axis, a slightly tighter vertical buff keeps this card's
        # natural height under the 6.6 cap without needing the corrective
        # scale-down this beat's first 2 drafts both needed (each of which
        # shrank the wider rule back down along with everything else).
        card = VGroup(top_rule, title, bottom_rule, handle).arrange(DOWN, buff=1.2)
        if card.height > 6.6:
            card.scale_to_fit_height(6.6)
        card.move_to(ORIGIN)

        self.play(Create(top_rule), run_time=0.35)
        self.play(FadeIn(title, shift=UP * 0.15), run_time=0.8)
        self.play(Create(bottom_rule), FadeIn(handle, shift=UP * 0.1), run_time=0.5)
        # animation sum = 1.65s; measured silent track = 4.05s
        self.wait(2.40)


