        title = fit(Text("Three Questions Before an Agent Acts", color=PALETTE["ink"], font_size=40), 12.0)
        title.to_edge(UP, buff=0.75)

        # buff=0.9 (not 0.4) — to_corner() measures from the hard FRAME edge,
        # not the safe area; GATE B measured the tighter buff's box at
        # (1.06,-3.6)-(6.71,-3.4), past both the safe-area right wall (6.3)
