        citation = fit(Text(
            "OWASP Top 10 for LLM Applications — LLM01: Prompt Injection",
            color=PALETTE["slate"], font_size=16,
        ), 6.0)
        citation.to_corner(DR, buff=0.9)

        self.play(Write(title), FadeIn(citation), run_time=0.5)

        intro = fit(Text("The check, before any example.", color=PALETTE["slate"], font_size=22), 10.0)
        intro.next_to(title, DOWN, buff=0.35)
        self.play(FadeIn(intro, shift=UP * 0.1), run_time=0.4)
        self.wait(6.3)
        self.play(FadeOut(intro, shift=UP * 0.1), run_time=0.3)

