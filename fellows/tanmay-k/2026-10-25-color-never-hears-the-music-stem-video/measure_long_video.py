#!/usr/bin/env python3
"""Measured gate for the long film's video (writes VIDEO-GATE-LONG.md).

 1. master: resolution, fps, codec, pix_fmt, audio (ffprobe)
 2. per-beat and master duration, video vs audio (must differ < 0.05 s)
 3. master loudness (ffmpeg ebur128: integrated LUFS, true peak)
 4. black frames: min mean luminance of every frame of every beat (decoded at 480x270), first/last frame means
 5. frame-difference activity: longest static stretch per beat (consecutive frames within 0.1% mean abs difference),
    and every stretch over 6 s listed with its beat and cause
 6. 'held at least 3 s' for the comparison beats: the key text elements are at full alpha at every sampled time in the last
    3 s (read from the scene function's own text log at the same times)
 7. the PROOF still-checks (4K size, ink margin >= 60 px, source band has ink) on the last frame of each beat, extracted
    from the video (B13's last frame is the fade to the cream page, so its frame at T-1.0 s is used)
 8. last frame vs the approved still, for the single-state beats (mean abs difference at 480x270)
Run: /opt/homebrew/bin/python3.12 measure_long_video.py
"""
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import build_long_motion as m                                     # noqa: E402
import build_long_stills as bl                                    # noqa: E402

BEATS = HERE / "_beats"
MASTER = m.MASTER
ORDER = m.ORDER
OUT = HERE / "VIDEO-GATE-LONG.md"
TMP = HERE / "_gate_tmp"
TMP.mkdir(exist_ok=True)


def run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True)


def probe(path, entries, sel):
    r = run(["ffprobe", "-v", "error", "-select_streams", sel, "-show_entries", entries, "-of", "json", str(path)])
    return json.loads(r.stdout)["streams"][0]


def gray_frames(path, w=480, h=270):
    p = subprocess.Popen(["ffmpeg", "-v", "error", "-i", str(path), "-vf", f"scale={w}:{h}", "-pix_fmt", "gray", "-f", "rawvideo", "-"],
                         stdout=subprocess.PIPE)
    raw = p.stdout.read()
    p.wait()
    return np.frombuffer(raw, dtype=np.uint8).reshape(-1, h, w)


def main():
    L = []
    P = L.append
    P("# VIDEO-GATE-LONG: measured gate for the long film's video\n")
    P("Generated by `measure_long_video.py` (this folder). Voice: Kokoro **am_onyx** (`make_audio.py` VOICE; audio not regenerated for the video).\n")
    # ---- 1 master
    v = probe(MASTER, "stream=width,height,r_frame_rate,codec_name,pix_fmt,bit_rate,duration,nb_frames", "v:0")
    a = probe(MASTER, "stream=codec_name,sample_rate,channels,bit_rate,duration", "a:0")
    P("## 1. Master\n")
    P(f"- file: `{MASTER.name}`")
    P(f"- video: {v['width']}x{v['height']}, {v['r_frame_rate']} fps, {v['codec_name']}, {v['pix_fmt']}, {v['nb_frames']} frames, duration {float(v['duration']):.3f} s")
    P(f"- audio: {a['codec_name']}, {a['sample_rate']} Hz, {a['channels']} ch, duration {float(a['duration']):.3f} s")
    P(f"- sibling (Week 27 long): 3840x2160, 30 fps, h264, yuv420p, aac 48 kHz mono, -14.7 LUFS / -1.8 dBFS\n")
    ok_master = (v["width"], v["height"]) == (3840, 2160) and v["r_frame_rate"] == "30/1" and v["pix_fmt"] == "yuv420p"
    # ---- 2 durations
    P("## 2. Durations, video vs audio (must differ by < 0.05 s)\n")
    P("| beat | video s | audio s | diff s | frames |\n|---|---|---|---|---|")
    worst = 0.0
    tot_v = 0.0
    for b in ORDER:
        vv = probe(BEATS / f"{b}.mp4", "stream=duration,nb_frames", "v:0")
        aa = probe(BEATS / f"{b}.mp4", "stream=duration", "a:0")
        d = abs(float(vv["duration"]) - float(aa["duration"]))
        worst = max(worst, d)
        tot_v += float(vv["duration"])
        P(f"| {b} | {float(vv['duration']):.3f} | {float(aa['duration']):.3f} | {d:.3f} | {vv['nb_frames']} |")
    md = abs(float(v["duration"]) - float(a["duration"]))
    P(f"| **master** | {float(v['duration']):.3f} | {float(a['duration']):.3f} | {md:.3f} | {v['nb_frames']} |")
    P(f"\nSum of beat video durations {tot_v:.3f} s vs master {float(v['duration']):.3f} s. Worst per-beat diff {worst:.3f} s. **{'PASS' if worst < 0.05 and md < 0.05 else 'FAIL'}**\n")
    # ---- 3 loudness
    r = run(["ffmpeg", "-nostats", "-hide_banner", "-i", str(MASTER), "-af", "ebur128=peak=true", "-f", "null", "-"])
    txt = r.stderr
    sm = txt[txt.rfind("Summary:"):]
    import re
    I = re.search(r"I:\s+(-?[\d.]+) LUFS", sm).group(1)
    LRA = re.search(r"LRA:\s+([\d.]+) LU", sm).group(1)
    TP = re.search(r"Peak:\s+(-?[\d.]+) dBFS", sm).group(1)
    P("## 3. Master loudness\n")
    P(f"- integrated **{I} LUFS**, true peak **{TP} dBFS**, LRA {LRA} LU (target I -14, TP <= -1.5; siblings -14.7 / -1.8)")
    P(f"- **{'PASS' if abs(float(I) + 14) <= 0.6 and float(TP) <= -1.4 else 'FAIL'}**\n")
    # ---- 4 + 5 frames
    P("## 4. Black frames (mean luminance of every frame, 480x270 gray; cream page = 249)\n")
    P("| beat | min mean over all frames | first frame | last frame |\n|---|---|---|---|")
    stat = {}
    stat_fr = {}
    for b in ORDER:
        fr = gray_frames(BEATS / f"{b}.mp4")
        mean = fr.reshape(len(fr), -1).mean(axis=1)
        diffs = np.abs(fr[1:].astype(np.int16) - fr[:-1].astype(np.int16)).reshape(len(fr) - 1, -1).mean(axis=1) / 255.0
        stat[b] = (mean, diffs, len(fr))
        stat_fr[b] = fr
        P(f"| {b} | {mean.min():.1f} | {mean[0]:.1f} | {mean[-1]:.1f} |")
    allmin = min(s[0].min() for s in stat.values())
    P(f"\nLowest mean luminance of any frame in the film: {allmin:.1f} (a black frame would read near 0). **{'PASS' if allmin > 150 else 'FAIL'}**\n")
    P("## 5. Frame-difference activity\n")
    P("The literal test (consecutive frames within 0.1% mean absolute difference) is not meaningful here: every element that fades in changes only a small part of a 480x270 frame, so the mean difference stays under 0.1% even while the picture is changing (a first run flagged whole beats as static for that reason). The measure used instead: a frame is *static* if fewer than 60 of its 129,600 pixels (0.046%) differ by more than 10 gray levels from the frame **one second later**; slow cloud drift (about 5 px/s) and fades register as change, a truly still frame does not. A run of static frames is reported in seconds (the true still time is the run plus 1 s).\n")
    P("| beat | longest static run (s) | runs over 6 s |\n|---|---|---|")
    causes = {"B10": "the 6-s answer hold: the countdown ring is the only motion and covers fewer than 60 px of change per second at 480x270",
              "B11": "the 3-s read-off hold", "B01": "the pick hold", "B12": "the hold", "B13": "the end card"}
    over = []
    K = m.FPS
    for b in ORDER:
        mean, _d, n = stat[b]
        fr = stat_fr[b]
        chg = np.array([(np.abs(fr[i + K].astype(np.int16) - fr[i].astype(np.int16)) > 10).sum() for i in range(n - K)])
        still = chg < 60
        runs, cur = [], 0
        for i, s in enumerate(still):
            if s:
                cur += 1
            else:
                if cur:
                    runs.append((i - cur, cur))
                cur = 0
        if cur:
            runs.append((len(still) - cur, cur))
        best = max([r[1] for r in runs], default=0)
        long_runs = [(a_ / m.FPS, d_ / m.FPS) for a_, d_ in runs if d_ / m.FPS > 6.0]
        lst = "; ".join(f"{a_:.1f}-{a_ + d_:.1f} s ({d_:.1f} s)" for a_, d_ in long_runs) or "none"
        if long_runs:
            over.append((b, lst))
        P(f"| {b} | {best / m.FPS:.2f} | {lst} |")
    P("")
    if over:
        P("Runs over 6 s, with cause (not failures: the holds are meant to be calm):")
        for b, lst in over:
            P(f"- {b}: {lst}: {causes.get(b, 'narration over a diagram with all elements in place')}")
    else:
        P("No static run over 6 s.")
    P("")
    # ---- 6 held >= 3 s
    P("## 6. 'Held at least 3 s' for the comparison beats\n")
    P("Method: the scene function's own text log, sampled at times across the last 3 s of the beat (the 3-s hold beats sample from T-2.5 s, since a 0.4 s fade-in precedes a 3-s hold). Every required element must be drawn at alpha >= 0.99 at every sample.\n")
    req = {
        "B01": ["1", "2", "pick one"],
        "B04": [".97", ".99", ".96", ".89", "correlation, not proof of mechanism", "MUSIC", "COLOR", "through feeling"],
        "B07": ["WHITE", "GREEN", ".88", ".96", ".97", ".95", "nonwestern scales: untested", "purity, in much of the West", "growth, in much of the West"],
        "B08": ["calm", "busy", "10 s", "3 s", "long scenes, 7–12 s each", "short scenes, 1–3 s each", "calm: cool colors   ·   busy: warm colors"],
        "B09": ["FAST CARTOON", "SLOWER CARTOON", "DRAW", "4 tasks, right afterwards", "pacing, not color  ·  immediate  ·  four-year-olds"],
        "B11": ["slow minor", "fast minor", "fast major", "✓ lighter than slow minor", "✓ less saturated than fast major", "= between"],
        "B12": ["the feelings disagree", "quick tune, blue-grey sky", "slow tune, yellow sky"],
    }
    P("| beat | window sampled | elements | result |\n|---|---|---|---|")
    held_ok = True
    for b, items in req.items():
        T = m.duration(b)
        start = T - 2.5 if b in ("B01", "B11") else T - 3.0
        times = [start + (T - 0.05 - start) * k / 6 for k in range(7)]
        fails = []
        for tt in times:
            cv = bl.new()
            m.FUNCS[b](cv, tt)
            seen = {}
            for text, size, alpha, x, y in cv.log:
                seen[text] = max(seen.get(text, 0), alpha)
            for it in items:
                if seen.get(it, 0) < 0.99:
                    fails.append((round(tt, 2), it, seen.get(it, 0)))
        held_ok &= not fails
        P(f"| {b} | {start:.1f}-{T:.1f} s (7 samples) | {len(items)} | {'PASS' if not fails else 'FAIL ' + str(fails[:3])} |")
    P(f"\n**{'PASS' if held_ok else 'FAIL'}**. Non-text elements (B11's dots, B09's bars, B08's blocks, B04's dots and arrows) arrive by the timeline: B11 dots by 10.5 s of 23.2 s, B09 bars by 12.9 s of 20.7 s, B08 blocks by 8 s of 20 s, B04 diagram by 8 s of 26.4 s, all before the sampled windows.\n")
    # ---- 7 proof still-checks on last frames
    P("## 7. PROOF still-checks on frames taken from the video (last frame of each beat)\n")
    P("| beat | frame at | 4K | ink margin >= 60 px | source band has ink | ink bbox |\n|---|---|---|---|---|---|")
    bad = 0
    for b in ORDER:
        T = m.nframes(b) / m.FPS
        at = T - 1.0 if b == "B13" else T - 1.0 / m.FPS
        png = TMP / f"{b}_last.png"
        if b == "B13":
            run(["ffmpeg", "-y", "-v", "error", "-ss", f"{at:.4f}", "-i", str(BEATS / f"{b}.mp4"), "-frames:v", "1", str(png)])
        else:
            run(["ffmpeg", "-y", "-v", "error", "-sseof", "-0.06", "-i", str(BEATS / f"{b}.mp4"), "-update", "1", "-frames:v", "1", str(png)])
        im = Image.open(png).convert("RGB")
        arr = np.asarray(im).astype(int)
        mask = np.abs(arr - np.array([250, 249, 245])).sum(axis=2) > 14
        ys, xs = np.where(mask)
        Wd, Hd = im.size
        bb = (xs.min(), ys.min(), xs.max(), ys.max())
        marg = bb[0] >= 60 and bb[1] >= 60 and bb[2] <= Wd - 60 and bb[3] <= Hd - 60
        band = mask[int(Hd * 0.90): int(Hd * 0.985), :].sum() > 200
        ok = (Wd, Hd) == (3840, 2160) and marg and (band or b == "B13")
        bad += not ok
        P(f"| {b} | {at:.2f} s | {(Wd, Hd) == (3840, 2160)} | {marg} | {band if b != 'B13' else 'n/a (end card)'} | {tuple(int(q) for q in bb)} {'' if ok else '  <-- CHECK'} |")
    P(f"\nFlags: {bad}. **{'PASS' if not bad else 'FAIL'}**\n")
    # ---- 8 last frame vs approved still
    P("## 8. Last frame vs the approved still (single-state beats; mean abs difference at 480x270, clouds drift so a few % is expected)\n")
    P("| beat | still | difference |\n|---|---|---|")
    pairs = {"B02": "B02", "B04": "B04", "B06": "B06", "B07": "B07", "B08": "B08", "B09": "B09", "B11": "B11", "B12": "B12", "B03": "B03-b",
             "B05": "B05-b", "B10": "B10-a", "B13": "B13", "B01": "B01-b"}
    for b, st in pairs.items():
        T = m.nframes(b) / m.FPS
        png = TMP / f"{b}_last.png"
        a1 = np.asarray(Image.open(png).convert("L").resize((480, 270))).astype(int)
        a2 = np.asarray(Image.open(HERE / "_stills" / f"{st}-16x9.png").convert("L").resize((480, 270))).astype(int)
        P(f"| {b} | {st} | {np.abs(a1 - a2).mean() / 255 * 100:.2f}% |")
    P("\n(B03, B05, B10 and B01 end in the still's second state or a later state of it; B10's last frame has the ring and the four-step card the still does not show together; B12 ends with extra caption text; so those read higher.)\n")
    OUT.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
