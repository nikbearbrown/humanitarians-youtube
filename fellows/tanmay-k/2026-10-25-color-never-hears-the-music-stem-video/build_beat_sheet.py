#!/usr/bin/env python3
"""build_beat_sheet.py: beat_sheet.json (long) and beat_sheet-short.json from the signed script and the measured audio.

The words come from the script (Gate P signed); the clock comes from the measured audio (mp3/timings.json and
short/mp3/timings_short.json); nothing is hand-edited. Run from the working folder:  python3 build_beat_sheet.py
Reads:  BEATS-DRAFT.md (topic video) or SCRIPT.md (work video); SHORT-SCRIPT.md; the two timings files if present.
Writes: beat_sheet.json, beat_sheet-short.json, and SHOTLIST.md / SHOTLIST-SHORT.md (one row per beat from the script's own
        visual and source text).
"""
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LONG_SRC = HERE / ("BEATS-DRAFT.md" if (HERE / "BEATS-DRAFT.md").exists() else "SCRIPT.md")
SHORT_SRC = next(p for p in (HERE / "SHORT-SCRIPT.md", HERE / "short" / "SHORT-SCRIPT.md") if p.exists())
TIM_LONG = next((p for p in (HERE / "mp3" / "timings.json",) if p.exists()), None)
TIM_SHORT = next((p for p in (HERE / "short" / "mp3" / "timings_short.json", HERE / "mp3" / "timings_short.json") if p.exists()), None)


def blocks(text, prefix):
    """yield (id, title, secs, tone, body) for every beat or line block."""
    pat = re.compile(r"^(?:\*\*|### )(" + prefix + r"\d\d) · ([^·\n*]+?)(?: · ~(\d+) s(?: \+ \d+ s hold)?)?(?:\*\*)?(?: \(tone: ([^)]*)\))?\s*$", re.M)
    ms = list(pat.finditer(text))
    for i, m in enumerate(ms):
        end = ms[i + 1].start() if i + 1 < len(ms) else len(text)
        body = text[m.end(): end]
        body = re.split(r"\n#{2,3} |\n\*\*(?:Runtime|Notes)", body)[0]
        yield m.group(1), m.group(2).strip().rstrip("*"), m.group(3), m.group(4), body


def narration(body):
    return " ".join(l[2:].strip() for l in body.splitlines() if l.startswith("> "))


def field(body, *names):
    for n in names:
        m = re.search(r"\*" + re.escape(n) + r":\*\s*(.*?)(?=\n\s*\n|\n\*[A-Z][a-z ]+:\*|\Z)", body, re.S)
        if m:
            return re.sub(r"\s+", " ", m.group(1)).strip()
    return ""


def long_sheet():
    text = LONG_SRC.read_text()
    tim = json.loads(TIM_LONG.read_text()) if TIM_LONG else {}
    beats, off = [], 0.0
    for bid, title, secs, tone, body in blocks(text, "B"):
        t = tim.get(bid, {})
        words = narration(body)
        d = t.get("duration_s")
        beats.append({"beat_id": bid, "title": title.upper(), "tone": tone or "", "narration_text": words,
                      "on_screen": field(body, "Visual", "On screen"), "source_on_screen": field(body, "Source on screen", "Source"),
                      "word_count": len(words.split()), "planned_s": int(secs) if secs else None,
                      "start_s": round(off, 2) if d else None, "narration_s": t.get("narration_end_s"),
                      "hold_after_narration_s": t.get("hold_s"), "duration_s": d})
        off += d or 0.0
    return beats, round(off, 2)


def short_sheet():
    text = SHORT_SRC.read_text()
    tim = json.loads(TIM_SHORT.read_text()) if TIM_SHORT else {}
    by = {}
    for s in tim.get("sentences", []):
        by.setdefault(s["line"], []).append(s)
    beats = []
    for lid, title, secs, tone, body in blocks(text, "S"):
        words = narration(body)
        ss = by.get(lid)
        beats.append({"beat_id": lid, "title": title.upper(), "tone": tone or "", "narration_text": words,
                      "on_screen": field(body, "On screen"), "source_on_screen": field(body, "Source"),
                      "word_count": len(words.split()), "planned_s": int(secs) if secs else None,
                      "start_s": round(ss[0]["start"], 2) if ss else None, "end_s": round(ss[-1]["end"], 2) if ss else None})
    return beats, tim.get("duration_s")


def shotlist(beats, title, kind):
    L = [f"# SHOTLIST: {title} ({kind})", "",
         "One row per beat, from the script's own visual and source text. Every figure on screen is read from a committed file or the cited paper, never typed. Generated by `build_beat_sheet.py`.", "",
         "| Beat | Shot | Source or evidence on screen | Measured |", "|---|---|---|---|"]
    for b in beats:
        meas = f"{b.get('duration_s'):.1f} s" if b.get("duration_s") else (f"{b['start_s']}–{b['end_s']} s" if b.get("end_s") else "")
        L.append(f"| {b['beat_id']} {b['title'].title()} | {b['on_screen'].replace('|', '/')} | {b['source_on_screen'].replace('|', '/')} | {meas} |")
    return "\n".join(L) + "\n"


def main():
    title_m = re.search(r"\*\*Working title:\*\* \*([^*]+)\*|^# SCRIPT: \*([^*]+)\*", LONG_SRC.read_text(), re.M)
    title = next(g for g in title_m.groups() if g) if title_m else LONG_SRC.stem
    lb, ld = long_sheet()
    sb, sd = short_sheet()
    meta = {"title": title, "voice_kokoro": "am_onyx", "master": "3840x2160 @ 30 fps", "beats": len(lb), "duration_s": ld,
            "clock": "MEASURED: Kokoro audio (mp3/timings.json); not hand-edited",
            "note": "words come from the signed script; figures on screen are read from committed files or the cited paper, never typed"}
    (HERE / "beat_sheet.json").write_text(json.dumps({"metadata": meta, "beats": lb}, indent=1, ensure_ascii=False))
    smeta = dict(meta, master="2160x3840 @ 30 fps", beats=len(sb), duration_s=sd, clock="MEASURED: Kokoro audio (short/mp3/timings_short.json); not hand-edited")
    (HERE / "beat_sheet-short.json").write_text(json.dumps({"metadata": smeta, "beats": sb}, indent=1, ensure_ascii=False))
    (HERE / "SHOTLIST.md").write_text(shotlist(lb, title, "long film, 16:9"))
    (HERE / "SHOTLIST-SHORT.md").write_text(shotlist(sb, title, "Short, 9:16"))
    print(f"{len(lb)} beats ({ld} s), {len(sb)} Short lines ({sd} s)")


if __name__ == "__main__":
    main()
