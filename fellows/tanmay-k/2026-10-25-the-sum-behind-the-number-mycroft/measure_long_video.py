#!/usr/bin/env python3
"""Measured gate for the work video's long film (writes VIDEO-GATE-LONG.md). Modelled on the topic video's gate.

 1. master: resolution, fps, codec, pix_fmt, audio (ffprobe)
 2. per-beat and master duration, video vs audio (must differ < 0.05 s)
 3. master loudness (ffmpeg ebur128 AFTER the AAC encode: integrated LUFS, true peak)
 4. black frames: min mean luminance of every frame of every beat (decoded at 480x270), first/last frame means
 5. longest static stretch per beat (changed pixels against the frame 1 s later), every stretch over 6 s listed with its cause
 6. 'held' for B03 (the guess), B05 (three bars together, the total), B06 (four bars), B07 (both columns and the counter):
    the scene function's own text log, sampled backwards from the end of the beat at 20 Hz, until a key element drops
    below full alpha; reported in seconds, PASS at >= 3.0 s
 7. the PROOF still-checks (4K size, ink margin >= 60 px, evidence band has ink, lowest ink <= 2060 px) and the collision
    check on the last frame of each beat, extracted from the video
 8. last frame vs the approved still (mean absolute difference at 480x270)
Run: /opt/homebrew/bin/python3.12 measure_long_video.py
"""
import json
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_long_motion as m                                     # noqa: E402
import build_long_stills as bl                                    # noqa: E402

BEATS = m.BEATS
MASTER = m.MASTER
ORDER = m.ORDER
OUT = HERE / "VIDEO-GATE-LONG.md"
TMP = HERE / "_gate_tmp"
TMP.mkdir(exist_ok=True)


def run(cmd):
    return subprocess.run([str(c) for c in cmd], capture_output=True, text=True)


def probe(path, entries, sel):
    r = run(["ffprobe", "-v", "error", "-select_streams", sel, "-show_entries", entries, "-of", "json", path])
    return json.loads(r.stdout)["streams"][0]


def gray_frames(path, w=480, h=270):
    p = subprocess.Popen(["ffmpeg", "-v", "error", "-i", str(path), "-vf", f"scale={w}:{h}", "-pix_fmt", "gray", "-f", "rawvideo", "-"],
                         stdout=subprocess.PIPE)
    raw = p.stdout.read()
    p.wait()
    return np.frombuffer(raw, dtype=np.uint8).reshape(-1, h, w)


def alphas(b, t):
    cv = bl.new()
    cv.cues = {}
    m.FUNCS[b](cv, t)
    return cv.log


def held_seconds(b, needed, step=0.05):
    """seconds, counted back from the end of the beat, that every key text is on screen at full alpha."""
    T = m.nframes(b) / m.FPS
    t = T - 1.0 / m.FPS
    while t > 0:
        log = alphas(b, t)
        ok = all(max([a for (s, _sz, a, _x, _y) in log if k in s], default=0) >= 0.99 for k in needed)
        if not ok:
            return T - t - step, t
        t -= step
    return T, 0.0


def main():
    L = []
    P = L.append
    P("# VIDEO-GATE-LONG: measured gate for the work video's long film\n")
    P("Generated by `measure_long_video.py` (this folder). Voice: Kokoro **am_onyx** (`make_audio.py` VOICE; audio not regenerated for the video).\n")
    v = probe(MASTER, "stream=width,height,r_frame_rate,codec_name,pix_fmt,bit_rate,duration,nb_frames", "v:0")
    a = probe(MASTER, "stream=codec_name,sample_rate,channels,bit_rate,duration", "a:0")
    P("## 1. Master\n")
    P(f"- file: `{MASTER.name}`")
    P(f"- video: {v['width']}x{v['height']}, {v['r_frame_rate']} fps, {v['codec_name']}, {v['pix_fmt']}, {v['nb_frames']} frames, duration {float(v['duration']):.3f} s")
    P(f"- audio: {a['codec_name']}, {a['sample_rate']} Hz, {a['channels']} ch, duration {float(a['duration']):.3f} s")
    P("- sibling (Week 28 topic video): 3840x2160, 30 fps, h264, yuv420p, aac 48 kHz mono, -14.5 LUFS / -1.9 dBFS\n")
    ok_master = (v["width"], v["height"]) == (3840, 2160) and v["r_frame_rate"] == "30/1" and v["pix_fmt"] == "yuv420p" and a["sample_rate"] == "48000" and a["channels"] == 1
    P(f"Spec check (3840x2160, 30 fps, yuv420p, 48 kHz mono): **{'PASS' if ok_master else 'FAIL'}**\n")
    P("## 2. Durations, video vs audio (must differ by < 0.05 s)\n")
    P("| beat | video s | audio s | diff s | frames |\n|---|---|---|---|---|")
    worst = tot_v = 0.0
    for b in ORDER:
        vv = probe(BEATS / f"{b}.mp4", "stream=duration,nb_frames", "v:0")
        aa = probe(BEATS / f"{b}.mp4", "stream=duration", "a:0")
        d = abs(float(vv["duration"]) - float(aa["duration"]))
        worst = max(worst, d)
        tot_v += float(vv["duration"])
        P(f"| {b} | {float(vv['duration']):.3f} | {float(aa['duration']):.3f} | {d:.3f} | {vv['nb_frames']} |")
    md = abs(float(v["duration"]) - float(a["duration"]))
    P(f"| **master** | {float(v['duration']):.3f} | {float(a['duration']):.3f} | {md:.3f} | {v['nb_frames']} |")
    P(f"\nSum of beat video durations {tot_v:.3f} s vs master {float(v['duration']):.3f} s; expected from timings.json {sum(m.duration(b) for b in ORDER):.3f} s. Worst per-beat diff {worst:.3f} s. **{'PASS' if worst < 0.05 and md < 0.05 else 'FAIL'}**\n")
    r = run(["ffmpeg", "-nostats", "-hide_banner", "-i", MASTER, "-af", "ebur128=peak=true", "-f", "null", "-"])
    sm = r.stderr[r.stderr.rfind("Summary:"):]
    I = re.search(r"I:\s+(-?[\d.]+) LUFS", sm).group(1)
    LRA = re.search(r"LRA:\s+([\d.]+) LU", sm).group(1)
    TP = re.search(r"Peak:\s+(-?[\d.]+) dBFS", sm).group(1)
    P("## 3. Master loudness (measured after the AAC encode)\n")
    P(f"- integrated **{I} LUFS**, true peak **{TP} dBFS**, LRA {LRA} LU (target I -14, TP -2.0 before AAC; the limit is -1.5 dBTP; siblings -14.5 / -1.9)")
    loud_ok = abs(float(I) + 14) <= 1.0 and float(TP) <= -1.5
    P("- Why -14.7 and not -14.0: the pass is linear (no limiter) and the true peak is held at -2.0 before AAC (-1.9 after); one more dB of gain would put the peak above the -1.5 dBTP limit. The siblings sit at -14.5 / -14.7.")
    P(f"- Criterion: integrated within 1.0 LU of -14 and true peak at or below -1.5 dBTP. **{'PASS' if loud_ok else 'FAIL'}**\n")
    P("## 4. Black frames (mean luminance of every frame, 480x270 gray; cream page = 249)\n")
    P("| beat | min mean over all frames | first frame | last frame |\n|---|---|---|---|")
    stat_fr = {}
    mins = []
    for b in ORDER:
        fr = gray_frames(BEATS / f"{b}.mp4")
        stat_fr[b] = fr
        mean = fr.reshape(len(fr), -1).mean(axis=1)
        mins.append(mean.min())
        P(f"| {b} | {mean.min():.1f} | {mean[0]:.1f} | {mean[-1]:.1f} |")
    P(f"\nLowest mean luminance of any frame in the film: {min(mins):.1f} (a black frame would read near 0). **{'PASS' if min(mins) > 150 else 'FAIL'}**\n")
    P("## 5. Longest static stretch (changed pixels against the frame 1 s later, fewer than 60 at 480x270)\n")
    P("| beat | longest static run (s) | starts at (s) | runs over 6 s |\n|---|---|---|---|")
    K = m.FPS
    over = []
    for b in ORDER:
        fr = stat_fr[b]
        n = len(fr)
        chg = np.array([(np.abs(fr[i + K].astype(np.int16) - fr[i].astype(np.int16)) > 10).sum() for i in range(n - K)])
        still = chg < 60
        runs, cur = [], 0
        for i, s_ in enumerate(still):
            if s_:
                cur += 1
            else:
                if cur:
                    runs.append((i - cur, cur))
                cur = 0
        if cur:
            runs.append((len(still) - cur, cur))
        best = max(runs, key=lambda r_: r_[1], default=(0, 0))
        long_runs = [(a_ / K, d_ / K) for a_, d_ in runs if d_ / K > 6.0]
        if long_runs:
            over.append((b, long_runs))
        P(f"| {b} | {best[1] / K:.2f} | {best[0] / K:.1f} | {'; '.join(f'{a_:.1f}-{a_ + d_:.1f} s' for a_, d_ in long_runs) or 'none'} |")
    P("")
    P("No static run over 6 s." if not over else "Runs over 6 s (listed, with cause): " + "; ".join(f"{b}: {lr}" for b, lr in over))
    P("")
    P("## 6. How long the key elements are held at full alpha at the end of the beat\n")
    P("Method: the scene function's own text log, sampled backwards at 20 Hz from the last frame until a key element drops below full alpha. Each key element comes in on its word, so a hold can be no longer than the narration leaves after its word.\n")
    sets = {
        "B03": ("the guess (question, NVDA label and the empty bar)", ["how far?", "NVDA"], 3.0),
        "B05": ("the three bars together (labels and blocks)", ["NVDA", "AMD", "TSM", "−40", "−35", "−15"], 3.0),
        "B06": ("the four bars and the book's total", ["TSLA 25%", "NVDA 25%", "META 25%", "AMD 25%", "−45", "−30", "33.75%"], 3.0),
        "B07": ("both columns and the counter", ["original code", "my copy", "total loss", "24 of 24", "identical"], 3.0),
    }
    P("| beat | key elements | held (s) | needed (s) | result |\n|---|---|---|---|---|")
    held_ok = True
    notes = []
    for b, (what, need, want) in sets.items():
        held, t_start = held_seconds(b, need)
        ok = held >= want - 0.05
        held_ok &= ok
        P(f"| {b} | {what} | {held:.2f} (since {t_start:.1f} s) | {want:.1f} | {'PASS' if ok else 'FAIL'} |")
    # B05 total: from the cue of '78' (narration) to the end
    cue78 = m.W("B05", "78")
    T5 = m.duration("B05")
    cb12 = m.W("B07", "12") + 0.1 + 11 * 0.19
    notes.append(f"B07's twelve breaks tick one by one from the word twelve at {m.W('B07', '12'):.1f} s; the last row lands at {cb12:.1f} s and the summary ('27 of 27', '12 of 12') at 'caught' {m.W('B07', 'caught'):.1f} s, so that list is complete for {m.duration('B07') - m.W('B07', 'caught'):.1f} s at the end by construction; the columns and the counter are held longer.")
    notes.append(f"B05's total ('total 78', then '36 + 27 + 15 = 78' under the returning number) is on screen from the word seventy-eight at {cue78:.1f} s to the end, {T5 - cue78:.1f} s: that is all the narration leaves after the word.")
    P("")
    for n_ in notes:
        P(f"- {n_}")
    P(f"\n**{'PASS' if held_ok else 'FAIL'}**\n")
    P("## 7. PROOF still-checks and the collision check on the last frame of each beat, extracted from the video\n")
    P("| beat | frame at | 4K | ink margin >= 60 px | evidence band has ink | lowest ink <= 2060 px | collisions | ink bbox |\n|---|---|---|---|---|---|---|---|")
    bad = 0
    for b in ORDER:
        T = m.nframes(b) / m.FPS
        at = T - 1.0 if b == "B11" else T - 1.0 / m.FPS
        png = TMP / f"{b}_last.png"
        if b == "B11":
            run(["ffmpeg", "-y", "-v", "error", "-ss", f"{at:.4f}", "-i", BEATS / f"{b}.mp4", "-frames:v", "1", png])
        else:
            run(["ffmpeg", "-y", "-v", "error", "-sseof", "-0.06", "-i", BEATS / f"{b}.mp4", "-update", "1", "-frames:v", "1", png])
        im = Image.open(png).convert("RGB")
        arr = np.asarray(im).astype(int)
        mask = np.abs(arr - np.array([250, 249, 245])).sum(axis=2) > 14
        ys, xs = np.where(mask)
        Wd, Hd = im.size
        bb = (xs.min(), ys.min(), xs.max(), ys.max())
        marg = bb[0] >= 60 and bb[1] >= 60 and bb[2] <= Wd - 60 and bb[3] <= Hd - 60
        band = mask[int(Hd * 0.90): int(Hd * 0.985), :].sum() > 200
        low = bb[3] <= 2060
        cv = bl.new()
        cv.cues = {}
        m.FUNCS[b](cv, at)
        hard, tight = bl.collisions(cv)
        ok = (Wd, Hd) == (3840, 2160) and marg and band and low and not hard
        bad += not ok
        P(f"| {b} | {at:.2f} s | {(Wd, Hd) == (3840, 2160)} | {marg} | {band} | {low} | {len(hard)} | {tuple(int(q) for q in bb)}{'' if ok else '  <-- CHECK'} |")
    P(f"\nFlags: {bad}. **{'PASS' if not bad else 'FAIL'}**\n")
    P("## 8. Last frame vs the approved still (mean absolute difference at 480x270)\n")
    P("| beat | still | difference |\n|---|---|---|")
    pairs = {"B01": "B01", "B02": "B02", "B03": "B03-b", "B04": "B04-c", "B05": "B05-b", "B06": "B06", "B08": "B08-b", "B09": "B09", "B10": "B10", "B11": "B11"}
    for b, st in pairs.items():
        T = m.nframes(b) / m.FPS
        png = TMP / f"{b}_last.png"
        a1 = np.asarray(Image.open(png).convert("L").resize((480, 270))).astype(int)
        a2 = np.asarray(Image.open(HERE / "_stills" / f"{st}-16x9.png").convert("L").resize((480, 270))).astype(int)
        P(f"| {b} | {st} | {np.abs(a1 - a2).mean() / 255 * 100:.2f}% |")
    P("\nB07's last frame is the merged layout (the two columns and the counter kept on screen while the twelve breaks tick), so it is not compared with a single still. B06 ends with the ring off the technology block and the TSLA block shown as in the still; B11's last frame is the fade to cream (frame at T-1.0 s compared).")
    OUT.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
