#!/usr/bin/env python3
"""beat_sheet.json (source of truth for the build) and SHOTLIST.md, from BEATS-DRAFT.md + the measured audio clock.

BEATS-DRAFT.md holds narration, tone, on-screen description and source line per beat.
mp3/timings.json holds the measured Kokoro durations and Whisper word times; _motion/plan.json holds the reveal cues.
Run: python3 build_beat_sheet.py   (after make_audio.py and build_motion.py --plan)
"""
import json, re
from pathlib import Path
HERE = Path(__file__).parent
HEAD = re.compile(r"^\*\*(B\d+\w*) · ([^·]+?) · ~(\d+) s( \+ (\d+) s hold)?\*\* \(tone: ([^)]*)\)", re.M)
src = (HERE / "BEATS-DRAFT.md").read_text()
timings = json.loads((HERE / "mp3" / "timings.json").read_text())
plan = json.loads((HERE / "_motion" / "plan.json").read_text())
starts = json.loads((HERE / "_beats" / "beat_starts.json").read_text())
ms = list(HEAD.finditer(src)); beats = []; act = ""
for i, m in enumerate(ms):
    pre = src[(ms[i - 1].end() if i else 0): m.start()]
    for h in re.findall(r"^### (.+)$", pre, re.M): act = h.strip()
    blk = src[m.end(): ms[i + 1].start() if i + 1 < len(ms) else len(src)]
    g = lambda tag: next((l[len(tag):].strip().rstrip("*") for l in blk.splitlines() if l.startswith(tag)), "")
    bid = m.group(1)
    beats.append({
        "beat_id": bid, "act": act, "title": m.group(2).strip(), "tone": m.group(6),
        "narration_text": " ".join(l[2:].strip() for l in blk.splitlines() if l.startswith("> ")),
        "on_screen": g("*Visual:*"), "source_line": g("*Source:*"),
        "planned_s": int(m.group(3)), "hold_after_narration_s": int(m.group(5) or 0),
        "start_s": round(starts[bid], 3), "duration_s": timings[bid]["duration_s"],
        "narration_end_s": timings[bid]["narration_end_s"],
        "reveal_cues": [{"stage": s, "at_s": t} for s, t in plan[bid]["cues"]],
    })
sheet = {"metadata": {"title": "The Birthday Paradox: Three Things You Could Change", "voice_kokoro": "am_onyx",
                      "master": "3840x2160 @ 30 fps", "beats": len(beats),
                      "duration_s": round(sum(b["duration_s"] for b in beats), 2),
                      "note": "audio is the clock; reveal_cues are on the Whisper word clock (mp3/timings.json); not hand-edited"},
         "beats": beats}
(HERE / "beat_sheet.json").write_text(json.dumps(sheet, indent=1, ensure_ascii=False))
rows = ["# SHOTLIST: The Birthday Paradox: Three Things You Could Change", "",
        "Generated by `build_beat_sheet.py` from `BEATS-DRAFT.md`. One slate per beat, drawn in code (`build_slates.py`); no generated imagery, no stock, no third-party images.",
        "", "| Beat | Start | Length | On screen | Source line | Reveals (stage at seconds) |", "|---|---|---|---|---|---|"]
for b in beats:
    cues = ", ".join(f"{c['stage']}@{c['at_s']:.1f}" for c in b["reveal_cues"][1:]) or "none"
    rows.append(f"| {b['beat_id']} {b['title'].title()} | {b['start_s']:.1f} s | {b['duration_s']:.1f} s | {b['on_screen']} | {b['source_line'] or 'none needed'} | {cues} |")
(HERE / "SHOTLIST.md").write_text("\n".join(rows) + "\n")
print(len(beats), "beats;", sheet["metadata"]["duration_s"], "s")
