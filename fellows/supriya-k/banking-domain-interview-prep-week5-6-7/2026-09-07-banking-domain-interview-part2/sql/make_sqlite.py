"""Derive the SQLite-runnable copy of each MySQL query shown on screen.

The ONLY change allowed: MySQL's DATE_FORMAT(x, fmt) -> SQLite's strftime(fmt, x), which
produce identical strings for the formats used here ('%Y-%m-01', '%Y-%m'). Everything else
(CTEs, SUM() OVER with an explicit ROWS frame, ROW_NUMBER, WHERE placement) is the same SQL in
both engines. The script refuses to write a copy if anything else would differ.
Run:  python3 make_sqlite.py && sqlite3 cascade.db < cascade.sql && sqlite3 -header -column cascade.db < X.sqlite.sql
"""
import re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
PAT = re.compile(r"DATE_FORMAT\((\w+), ('%Y-%m(?:-01)?')\)")
for src in sorted(HERE.glob("*.mysql.sql")):
    text = src.read_text()
    out = PAT.sub(lambda m: f"strftime({m.group(2)}, {m.group(1)})", text)
    if PAT.sub("X", text) != re.sub(r"strftime\('%Y-%m(?:-01)?', \w+\)", "X", out):
        sys.exit(f"{src.name}: conversion changed more than DATE_FORMAT -> strftime")
    if "DATE_FORMAT" in out:
        sys.exit(f"{src.name}: unconverted DATE_FORMAT left")
    dst = src.with_name(src.name.replace(".mysql.sql", ".sqlite.sql"))
    dst.write_text("-- AUTO-GENERATED by make_sqlite.py from " + src.name +
                   " (only change: DATE_FORMAT -> strftime)\n" + out)
    print(f"{src.name} -> {dst.name}")
