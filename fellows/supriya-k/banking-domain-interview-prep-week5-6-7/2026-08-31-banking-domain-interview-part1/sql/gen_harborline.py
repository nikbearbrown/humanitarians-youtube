"""Generate sql/harborline.sql — the book's Harborline Card Co. schema (Ch.9, verbatim) with an
invented, deterministic sample: a January 2025 cohort of 500 accounts and a February 2025 cohort
of 200 (so the cohort filter has something to exclude). One snapshot per account per month,
batch_id = 1 (no resubmitted batches, so no duplicate rows). Each January account follows a
non-improving delinquency path; its month-3/6/9 buckets are set by sorted assignment so the
cohort's bucket counts are exactly the targets below.
Run: python3 gen_harborline.py
"""
from pathlib import Path
BUCKETS = ["current", "30", "60", "90+", "charge_off"]
TARGET = {3: [460, 30, 8, 2, 0], 6: [420, 40, 25, 10, 5], 9: [390, 45, 30, 20, 15]}

def rank(counts, i):
    c = 0
    for r, n in enumerate(counts):
        c += n
        if i < c:
            return r
    raise ValueError

rows_a, rows_s = [], []
def month(y, m):
    y += (m - 1) // 12; m = (m - 1) % 12 + 1
    return f"{y}-{m:02d}-01"

for i in range(500):                                   # January 2025 cohort
    aid = 100001 + i
    rows_a.append(f"({aid}, {500001 + i}, '2025-01-01', 5000.00)")
    r3, r6, r9 = (rank(TARGET[k], i) for k in (3, 6, 9))
    assert r3 <= r6 <= r9
    for mob in range(1, 10):
        r = 0 if mob < 3 else r3 if mob < 6 else r6 if mob < 9 else r9
        rows_s.append(f"({aid}, '{month(2025, 1 + mob)}', '{BUCKETS[r]}', 1, '{month(2025, 1 + mob)} 06:00:00')")
for i in range(200):                                   # February 2025 cohort (excluded by the query)
    aid = 200001 + i
    rows_a.append(f"({aid}, {600001 + i}, '2025-02-01', 5000.00)")
    for mob in range(1, 9):
        r = 1 if (mob >= 3 and i % 5 == 0) else 0
        rows_s.append(f"({aid}, '{month(2025, 2 + mob)}', '{BUCKETS[r]}', 1, '{month(2025, 2 + mob)} 06:00:00')")

sql = """-- Harborline Card Co. (the book's invented card issuer, Ch.9) — GENERATED by gen_harborline.py.
-- Invented sample data: Jan 2025 cohort (500 accounts) + Feb 2025 cohort (200).
DROP TABLE IF EXISTS monthly_snapshots;
DROP TABLE IF EXISTS accounts;
CREATE TABLE accounts (
    account_id        INT PRIMARY KEY,
    customer_id       INT NOT NULL,
    origination_month DATE NOT NULL,
    credit_limit      DECIMAL(10,2) NOT NULL
);
CREATE TABLE monthly_snapshots (
    account_id     INT NOT NULL,
    snapshot_month DATE NOT NULL,
    dpd_bucket     VARCHAR(10) NOT NULL,
    batch_id       INT NOT NULL,
    load_ts        DATETIME NOT NULL,
    PRIMARY KEY (account_id, snapshot_month, batch_id)
);
"""
for name, rows in (("accounts", rows_a), ("monthly_snapshots", rows_s)):
    for k in range(0, len(rows), 500):
        sql += f"INSERT INTO {name} VALUES\n  " + ",\n  ".join(rows[k:k + 500]) + ";\n"
Path(__file__).with_name("harborline.sql").write_text(sql)
print(len(rows_a), "accounts,", len(rows_s), "snapshots")
