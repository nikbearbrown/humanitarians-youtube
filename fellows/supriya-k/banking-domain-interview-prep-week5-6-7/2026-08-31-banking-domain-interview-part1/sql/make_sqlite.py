"""Derive the SQLite-runnable copy of each MySQL query shown on screen.

Allowed changes (MySQL-only syntax -> the SQLite equivalent; nothing else may differ):
  1. DATE_FORMAT(x, '%Y-%m-01' | '%Y-%m')  ->  strftime(fmt, x)              (same strings)
  2. PERIOD_DIFF(DATE_FORMAT(a,'%Y%m'), DATE_FORMAT(b,'%Y%m'))
       -> (year(a)*12 + month(a)) - (year(b)*12 + month(b)), via strftime   (same integer)
  3. FIELD(col, 'v1', 'v2', ...)  ->  CASE col WHEN 'v1' THEN 1 WHEN 'v2' THEN 2 ... END
  4. ROUND(100 * x / y, 1)  ->  ROUND(100.0 * x / y, 1)   (SQLite's / on integers truncates;
     MySQL's / returns a decimal)
The script refuses to write a copy if anything else would change.
"""
import re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
ym = lambda e: f"(CAST(strftime('%Y', {e}) AS INTEGER) * 12 + CAST(strftime('%m', {e}) AS INTEGER))"
RULES = [
    (re.compile(r"PERIOD_DIFF\(\s*DATE_FORMAT\(([\w.]+), '%Y%m'\),\s*DATE_FORMAT\(([\w.]+), '%Y%m'\)\s*\)", re.S),
     lambda m: f"({ym(m.group(1))} - {ym(m.group(2))})"),
    (re.compile(r"DATE_FORMAT\(([\w.]+), ('%Y-%m(?:-01)?')\)"), lambda m: f"strftime({m.group(2)}, {m.group(1)})"),
    (re.compile(r"FIELD\((\w+), ((?:'[^']*'(?:, )?)+)\)"),
     lambda m: "CASE " + m.group(1) + " " + " ".join(f"WHEN {v} THEN {k + 1}" for k, v in
                                                    enumerate(re.findall(r"'[^']*'", m.group(2)))) + " END"),
    (re.compile(r"ROUND\(100 \* "), lambda m: "ROUND(100.0 * "),
]
for src in sorted(HERE.glob("*.mysql.sql")):
    text = out = src.read_text()
    for pat, fn in RULES:
        out = pat.sub(fn, out)
    probe = text
    for pat, _ in RULES:
        probe = pat.sub("X", probe)
    probe_out = out
    for p in (r"\(\(CAST\(strftime\('%Y', [\w.]+\) AS INTEGER\) \* 12 \+ CAST\(strftime\('%m', [\w.]+\) AS INTEGER\)\) - \(CAST\(strftime\('%Y', [\w.]+\) AS INTEGER\) \* 12 \+ CAST\(strftime\('%m', [\w.]+\) AS INTEGER\)\)\)",
              r"strftime\('%Y-%m(?:-01)?', [\w.]+\)", r"CASE \w+ (?:WHEN '[^']*' THEN \d+ ?)+END", r"ROUND\(100\.0 \* "):
        probe_out = re.sub(p, "X", probe_out)
    if probe != probe_out:
        sys.exit(f"{src.name}: conversion changed more than the four documented constructs")
    for bad in ("DATE_FORMAT", "PERIOD_DIFF", "FIELD("):
        if bad in out:
            sys.exit(f"{src.name}: unconverted {bad}")
    dst = src.with_name(src.name.replace(".mysql.sql", ".sqlite.sql"))
    dst.write_text(f"-- AUTO-GENERATED by make_sqlite.py from {src.name} (documented MySQL->SQLite swaps only)\n" + out)
    print(f"{src.name} -> {dst.name}")
