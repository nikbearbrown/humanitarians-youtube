"""Exports evidence/scene.json + evidence/results.json (written by tempo.py) into the Remotion scenes' data module.

Every waveform, band, spike, match score, tempo and beat the tempo scenes draw comes from that real run. B03's
autocorrelation and BPM rule are typeset with the toolkit's runtime/scripts/typeset_math.py (MathText ->
outlined SVG); the worked divisions use the run's own peak lags.

    python export_tempo_data.py
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLKIT = "D:/Rohan/Claude/HAI/RohanClaudeHAIbrutalist.art"
EV = os.path.join(HERE, "evidence")
OUT_TS = os.path.join(TOOLKIT, "runtime/remotion/src/scenes/tempo/tempoData.ts")
sys.path.insert(0, os.path.join(TOOLKIT, "runtime/scripts"))
sys.path.append(os.path.join(TOOLKIT, ".pydeps"))
from typeset_math import typeset  # noqa: E402

import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

S = json.load(open(os.path.join(EV, "scene.json"), encoding="utf-8"))
R = json.load(open(os.path.join(EV, "results.json"), encoding="utf-8"))
ex, dr = S["example"], S["drift"]

# the run's own peaks: the lags (in frames) nearest one beat and two beats, as seconds to 2 decimals
lags = np.array(ex["ac_lags_s"]); ac = np.array(ex["ac"])
def peak_near(sec):
    i = int(np.argmin(np.abs(lags - sec)))
    j = max(1, i - 3) + int(np.argmax(ac[max(1, i - 3): i + 4]))
    return float(lags[j]), float(ac[j])
one_s, one_v = peak_near(60 / ex["bpm"])
two_s, two_v = peak_near(120 / ex["bpm"])
assert one_v < two_v, "the example must show the two-beat repeat matching better (it is what B03 says)"
w1 = round(60 / 0.5); w2 = round(60 / 1.0)
eq = {
    "rule": typeset(r"r(\tau) = \sum_t o(t)\,o(t+\tau)"),
    "bpm": typeset(r"\mathrm{BPM} = 60 \,/\, \tau"),
    "half": typeset(r"60 \,/\, 0.5\,\mathrm{s} = " + f"{w1}"),
    "one": typeset(r"60 \,/\, 1.0\,\mathrm{s} = " + f"{w2}"),
}

# the 40 mel bands of the example as an image (ink on transparent, louder = darker; low bands at the bottom)
PUB = os.path.join(TOOLKIT, "runtime/remotion/public/tempo")
os.makedirs(PUB, exist_ok=True)
g = np.array(ex["bands"])[::-1]
a = np.clip((g - 0.3) / 0.6, 0, 1) ** 1.0 * 0.95
rgba = np.zeros(g.shape + (4,), np.uint8)
rgba[..., :3] = (61, 57, 41)
rgba[..., 3] = (a * 255).astype(np.uint8)
Image.fromarray(rgba, "RGBA").resize((g.shape[1] * 8, g.shape[0] * 8), Image.BILINEAR).save(os.path.join(PUB, "bands.png"))

# LOGO LAW: librosa is named on screen (B04, B05), so its own mark is shown (icons/logos/librosa)
import shutil  # noqa: E402
shutil.copy(os.path.join(TOOLKIT, "icons/logos/librosa/librosa-01.svg"), os.path.join(PUB, "librosa-01.svg"))

rows = R["rows"]
data = {
    "example": {k: ex[k] for k in ("style", "bpm", "seed", "show_s", "fps", "env", "beats", "onset", "ac_lags_s", "ac",
                                   "prior", "ac_at", "raw", "prior_pick")},
    "bands": {"src": "tempo/bands.png", "n": len(ex["bands"]), "frames": len(ex["bands"][0])},
    "peaks": {"oneBeat": {"s": round(one_s, 3), "v": round(one_v, 3)}, "twoBeats": {"s": round(two_s, 3), "v": round(two_v, 3)}},
    "rows": rows,
    "summary": R["summary"],
    "drift": dr,
    "eq": eq,
    "logo": {"librosa": "tempo/librosa-01.svg"},
    "evidenceSha256": hashlib.sha256(open(os.path.join(EV, "results.json"), "rb").read()).hexdigest(),
}
os.makedirs(os.path.dirname(OUT_TS), exist_ok=True)
with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* GENERATED by export_tempo_data.py in the reel folder\n"
             " * (books/humanitarians-ai/youtube/week-08/2026-10-16-how-apps-find-a-songs-tempo).\n"
             " * Every curve, tempo and beat here comes from a real run of tempo.py on synthetic\n"
             " * drum grooves (grooves.py). Do not hand-edit; re-run the exporter. */\n")
    fh.write("export const TMP = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"peaks: one beat {one_s:.3f} s = {one_v:.3f}, two beats {two_s:.3f} s = {two_v:.3f}")
print(f"wrote {OUT_TS} ({os.path.getsize(OUT_TS) / 1024:.0f} KB)")
