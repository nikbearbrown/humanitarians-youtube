"""Exports evidence/results.json (written by voice.py) into the Remotion scenes' data module (scenes/voice/voiceData.ts).

    python export_voice_data.py
"""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLKIT = "D:/Rohan/Claude/HAI/RohanClaudeHAIbrutalist.art"
EV = os.path.join(HERE, "evidence")
OUT_TS = os.path.join(TOOLKIT, "runtime/remotion/src/scenes/voice/voiceData.ts")

R = json.load(open(os.path.join(EV, "results.json"), encoding="utf-8"))
assert R["heteronym_right"] == 10 and R["heteronym_both"] == 2, "B03 says ten of sixteen, two words both ways"
# the reading of each normalisation case, as words a person can read (from the run's IPA), and its verdict
READ = {"Dr. Smith": ("doctor smith", True), "Main St.": ("main street", True),
        "1,024 bytes": ("one thousand twenty-four bytes", True), "in 2026": ("in two thousand twenty-six", True),
        "at 10:30": ("at ten thirty", True), "the 5th of May": ("the fifth of may", True),
        "It costs $3.50.": ("it costs dollar three. fifty", False)}
for n in R["normalise"]:
    n["reads"], n["ok"] = READ[n["text"]]
data = {**R, "evidenceSha256": hashlib.sha256(open(os.path.join(EV, "results.json"), "rb").read()).hexdigest()}
os.makedirs(os.path.dirname(OUT_TS), exist_ok=True)
with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* GENERATED by export_voice_data.py in the reel folder\n"
             " * (books/humanitarians-ai/youtube/week-10/2026-10-30-how-ai-voices-read-a-script).\n"
             " * Every IPA string here is the narrator's own G2P output (espeak-ng via kokoro-onnx), from voice.py.\n"
             " * Do not hand-edit; re-run the exporter. */\n")
    fh.write("export const VOICE = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"wrote {OUT_TS} ({os.path.getsize(OUT_TS) / 1024:.0f} KB)")
