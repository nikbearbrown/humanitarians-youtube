"""Writes the toolkit's scenes/recs/recsData.ts from this reel's evidence (recs.py). Run after recs.py."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = Path("D:/Rohan/Claude/HAI/RohanClaudeHAIbrutalist.art/runtime/remotion/src/scenes/recs/recsData.ts")
res = json.loads((HERE / "evidence" / "results.json").read_text(encoding="utf-8"))
sc = json.loads((HERE / "evidence" / "scene.json").read_text(encoding="utf-8"))

data = {
    "nSongs": res["n_songs"], "nUsers": res["n_users"], "nPlays": res["n_plays"], "k": res["k"],
    "genres": sc["genres"],
    "acc": res["accuracy"],
    "sameGenre": res["same_genre_nn"], "sameGenreBy": res["same_genre_by"],
    "exampleSong": sc["example_song"],
    "exampleUser": sc["example_user"],
    "pop": res["pop_bias"],
    "loopPlain": res["loop_plain"], "loopExplore": res["loop_explore"],
    "coldRank": res["cold_new_song_rank"],
    # the taste map: every song's vector projected to 2-D (first two principal components), with its genre
    "pca": sc["pca"], "pcaVar": sc["pca_var"],
}
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("/* GENERATED by export_recs_data.py in the reel folder\n"
               " * (books/humanitarians-ai/youtube/week-11/2026-11-06-how-spotify-picks-songs).\n"
               " * Every number here comes from a real run of recs.py (a made-up music service, not Spotify's data).\n"
               " * Do not hand-edit; re-run the exporter. */\n"
               f"export const RECS = {json.dumps(data, separators=(',', ':'))} as const;\n", encoding="utf-8", newline="\n")
print("wrote", OUT, f"({OUT.stat().st_size // 1024} KB)")
