"""Exports evidence/scene.json + evidence/results.json (written by anc.py) into the Remotion scenes' data module.

Every waveform, decibel figure and band the ANC scenes draw comes from that real run. B03's phase rule and its
two worked cases are typeset with the toolkit's runtime/scripts/typeset_math.py, using the run's own numbers.

    python export_anc_data.py
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLKIT = "D:/Rohan/Claude/HAI/RohanClaudeHAIbrutalist.art"
EV = os.path.join(HERE, "evidence")
OUT_TS = os.path.join(TOOLKIT, "runtime/remotion/src/scenes/anc/ancData.ts")
sys.path.insert(0, os.path.join(TOOLKIT, "runtime/scripts"))
sys.path.append(os.path.join(TOOLKIT, ".pydeps"))
from typeset_math import typeset  # noqa: E402

S = json.load(open(os.path.join(EV, "scene.json"), encoding="utf-8"))
R = json.load(open(os.path.join(EV, "results.json"), encoding="utf-8"))
rule = {r["hz"]: r for r in R["rule"]}
r100, r2k = rule[100], rule[2000]
assert abs(r100["phase_deg"] - 3.6) < 0.05 and abs(r2k["phase_deg"] - 72.0) < 0.05
eq = {
    "phase": typeset(r"\varphi = 360^{\circ} \cdot f \cdot t"),
    "resid": typeset(r"\mathrm{left\ over} = 2 \sin(\varphi / 2)"),
    "w100": typeset(r"360^{\circ} \times 100\,\mathrm{Hz} \times 0.1\,\mathrm{ms} = " + f"{r100['phase_deg']:.1f}" + r"^{\circ}"),
    "w2k": typeset(r"360^{\circ} \times 2000\,\mathrm{Hz} \times 0.1\,\mathrm{ms} = " + f"{r2k['phase_deg']:.0f}" + r"^{\circ}"),
}
data = {"waves": S, "types": R["types"], "bands": R["bands"], "rule": R["rule"], "f60": R["f60"], "conv": R["conv"],
        "model": R["model"], "eq": eq,
        "evidenceSha256": hashlib.sha256(open(os.path.join(EV, "results.json"), "rb").read()).hexdigest()}
os.makedirs(os.path.dirname(OUT_TS), exist_ok=True)
with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* GENERATED by export_anc_data.py in the reel folder\n"
             " * (books/humanitarians-ai/youtube/week-09/2026-10-23-how-noise-cancelling-headphones-work).\n"
             " * Every waveform and decibel figure here comes from a real run of anc.py (a simulated feedforward\n"
             " * FxLMS headphone on synthetic noise). Do not hand-edit; re-run the exporter. */\n")
    fh.write("export const ANC = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {OUT_TS} ({os.path.getsize(OUT_TS) / 1024:.0f} KB)")
