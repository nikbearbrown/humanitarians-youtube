"""Exports evidence/scene.json + evidence/results.json (written by key.py) into the Remotion scenes' data module.

Every chroma frame, profile, correlation and verdict the key scenes draw comes from that real run. B03's
correlation is typeset with the toolkit's runtime/scripts/typeset_math.py.

    python export_key_data.py
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLKIT = "D:/Rohan/Claude/HAI/RohanClaudeHAIbrutalist.art"
EV = os.path.join(HERE, "evidence")
OUT_TS = os.path.join(TOOLKIT, "runtime/remotion/src/scenes/keys/keyData.ts")
sys.path.insert(0, os.path.join(TOOLKIT, "runtime/scripts"))
sys.path.append(os.path.join(TOOLKIT, ".pydeps"))
from typeset_math import typeset  # noqa: E402

S = json.load(open(os.path.join(EV, "scene.json"), encoding="utf-8"))
R = json.load(open(os.path.join(EV, "results.json"), encoding="utf-8"))
pop_r = S["pop"]["r"]
assert max(range(24), key=lambda i: pop_r[i]) == 0, "the example must come out C major (B03 says so)"
assert sorted(range(24), key=lambda i: -pop_r[i])[1] == 7, "the runner-up must be G major (B03 says so)"
min_r = S["minor"]["r"]
assert min_r[0] > min_r[12 + 9], "the A minor example must lose narrowly to C major (B05 says so)"
eq = {
    "corr": typeset(r"r = \frac{\sum_i (x_i-\bar{x})(y_i-\bar{y})}{\sqrt{\sum_i (x_i-\bar{x})^2 \, \sum_i (y_i-\bar{y})^2}}"),
    "cmaj": typeset(r"r_{\mathrm{C\ major}} = " + f"{pop_r[0]:.2f}"),
}
data = {
    "pop": S["pop"], "minor": S["minor"], "change": S["change"], "kk": S["kk"],
    "rows": R["rows"], "summary": R["summary"], "all": R["all"], "score": R["score"],
    "eq": eq,
    "evidenceSha256": hashlib.sha256(open(os.path.join(EV, "results.json"), "rb").read()).hexdigest(),
}
os.makedirs(os.path.dirname(OUT_TS), exist_ok=True)
with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* GENERATED by export_key_data.py in the reel folder\n"
             " * (books/humanitarians-ai/youtube/week-09/2026-10-23-how-apps-find-a-songs-key).\n"
             " * Every chroma frame, profile and verdict here comes from a real run of key.py on synthetic\n"
             " * Western songs (songs.py). Do not hand-edit; re-run the exporter. */\n")
    fh.write("export const KEY = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"C major r={pop_r[0]:.3f}, A minor r={pop_r[21]:.3f}; minor example C major {min_r[0]:.3f} vs A minor {min_r[21]:.3f}")
print(f"wrote {OUT_TS} ({os.path.getsize(OUT_TS) / 1024:.0f} KB)")
