"""Exports evidence/codec.json (written by codec.py) into the Remotion scenes' data module.

Every token, curve and percentage the token scenes draw comes from that real run. B03's residual sum and
token-rate arithmetic are typeset with the toolkit's runtime/scripts/typeset_math.py; the arithmetic is
computed here from the run's parameters (and the verified CD rate), never typed in.

    python export_tok_data.py
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLKIT = "D:/Rohan/Claude/HAI/RohanClaudeHAIbrutalist.art"
EV = os.path.join(HERE, "evidence")
OUT_TS = os.path.join(TOOLKIT, "runtime/remotion/src/scenes/tokens/tokData.ts")
sys.path.insert(0, os.path.join(TOOLKIT, "runtime/scripts"))
sys.path.append(os.path.join(TOOLKIT, ".pydeps"))
from typeset_math import typeset  # noqa: E402

D = json.load(open(os.path.join(EV, "codec.json"), encoding="utf-8"))
P = D["params"]
fps, bits = P["fps"], P["bits"]
tok4 = fps * 4
kbps4 = tok4 * bits / 1000
CD_KBPS = 44100 * 16 * 2 / 1000          # 1,411.2 kbit/s (verified, facts.md #9)
ratio = CD_KBPS / kbps4
song = 44100 * 2 * 180                   # a three-minute stereo song, in samples
eq = {
    "residual": typeset(r"x_t \approx C_1[k_1] + C_2[k_2] + C_3[k_3] + C_4[k_4]"),
    "rate": typeset(f"{fps:.2f}" + r"\ \mathrm{frames/s} \times 4 = " + f"{tok4:.0f}" + r"\ \mathrm{tokens/s}"),
    "bits": typeset(f"{tok4:.0f}" + r" \times " + f"{bits}" + r"\ \mathrm{bits} = " + f"{kbps4:.2f}" + r"\ \mathrm{kbit/s}"),
    "cd": typeset(f"{CD_KBPS:.1f}" + r"\ \mathrm{kbit/s} \div " + f"{kbps4:.2f}" + r" \approx " + f"{ratio:.0f}"),
    # phone-length versions: the same arithmetic, units moved to the sans caption above each row, so
    # the rows can be set large enough for the 9:16 type floor
    # (no subscripts on the phone: a subscript digit cannot reach the 9:16 type floor at any width that fits)
    # (three terms: the approx sign is short, and only a short row can be set large enough to clear the floor)
    "pResidual": typeset(r"F \approx A + B + C"),
    "pRate": typeset(f"{fps:.2f}" + r" \times 4 = " + f"{tok4:.0f}"),
    "pBits": typeset(f"{tok4:.0f}" + r" \times " + f"{bits}" + r" = " + f"{tok4 * bits:.0f}"),
    # exact (1411.2 / 3.75 = 376.32), so "=" rather than a short approx sign the phone floor can't hold
    "pCd": typeset(f"{CD_KBPS:.1f}" + r" \div " + f"{kbps4:.2f}" + r" = " + f"{CD_KBPS / kbps4:.2f}"),
}
data = {**D, "derived": {"tok4": tok4, "kbps4": kbps4, "cdKbps": CD_KBPS, "ratio": round(ratio), "songSamples": song},
        "eq": eq,
        "evidenceSha256": hashlib.sha256(open(os.path.join(EV, "codec.json"), "rb").read()).hexdigest()}
os.makedirs(os.path.dirname(OUT_TS), exist_ok=True)
with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* GENERATED by export_tok_data.py in the reel folder\n"
             " * (books/humanitarians-ai/youtube/week-07/2026-10-09-how-ai-music-turns-text-into-audio).\n"
             " * Every token, curve and number here comes from a real run of codec.py on synthetic\n"
             " * music (synth.py). Do not hand-edit; re-run the exporter. */\n")
    fh.write("export const TOK = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"4 codebooks: {tok4:.0f} tokens/s = {kbps4:.2f} kbit/s; CD {CD_KBPS:.1f} kbit/s = {ratio:.0f}x; 3-min stereo song {song:,} samples")
print(f"wrote {OUT_TS} ({os.path.getsize(OUT_TS) / 1024:.0f} KB)")
