"""Exports evidence/fingerprint.json (written by fingerprint.py) into the Remotion scenes' data module.

Every point, hash, vote and count the Shazam scenes draw comes from that real run. B03's offset rule and
its worked example are typeset with the toolkit's runtime/scripts/typeset_math.py (MathText -> outlined
SVG); the worked example is a real matching hash from the query, picked here, never typed in.

    python export_shazam_data.py
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLKIT = "D:/Rohan/Claude/HAI/RohanClaudeHAIbrutalist.art"
EV = os.path.join(HERE, "evidence")
OUT_TS = os.path.join(TOOLKIT, "runtime/remotion/src/scenes/shazam/shazamData.ts")
sys.path.insert(0, os.path.join(TOOLKIT, "runtime/scripts"))
sys.path.append(os.path.join(TOOLKIT, ".pydeps"))
from typeset_math import typeset  # noqa: E402

D = json.load(open(os.path.join(EV, "fingerprint.json"), encoding="utf-8"))
q = D["query"]
top = q["ranked"][0]
assert top["song"] == q["song"] and abs(top["offset_s"] - q["start"]) < 0.05, top
# a real matching pair on the winning offset, early in the clip (so the numbers are small and readable)
on = [p for p in D["pairs"][top["song"]] if abs((p[1] - p[0]) - top["offset_s"]) < 0.012 and 0.8 < p[0] < 2.5
      # the shown (rounded) digits must subtract exactly, or the screen arithmetic looks wrong
      and round(round(p[1], 2) - round(p[0], 2), 2) == round(top["offset_s"], 2)]
t_clip, t_song = on[0]
t_song, t_clip = round(t_song, 2), round(t_clip, 2)
diff = round(t_song - t_clip, 2)
assert abs(diff - top["offset_s"]) < 0.012
eq = {
    "rule": typeset(r"\Delta t = t_{\mathrm{song}} - t_{\mathrm{clip}}"),
    "worked": typeset(f"{t_song:.2f}" + r"\,\mathrm{s} - " + f"{t_clip:.2f}" + r"\,\mathrm{s} = " + f"{diff:.2f}" + r"\,\mathrm{s}"),
}
spec = D["spec"]
# the spectrograms as images (ink on transparent, louder = darker), so a scene draws one <Img>, not 18,000 cells
import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402
PUB = os.path.join(TOOLKIT, "runtime/remotion/public/shazam")
os.makedirs(PUB, exist_ok=True)
for name, grid in (("spec-clean.png", spec["grid"]), ("spec-noisy.png", spec["noisy_grid"])):
    g = np.array(grid)[::-1]                                  # row 0 is the lowest frequency: put it at the bottom
    a = np.clip((g - 0.05) / 0.55, 0, 1) ** 0.9 * 0.92
    rgba = np.zeros(g.shape + (4,), np.uint8)
    rgba[..., :3] = (61, 57, 41)
    rgba[..., 3] = (a * 255).astype(np.uint8)
    Image.fromarray(rgba, "RGBA").resize((g.shape[1] * 8, g.shape[0] * 4), Image.BILINEAR).save(os.path.join(PUB, name))
data = {
    "params": D["params"], "library": D["library"],
    "query": {k: v for k, v in q.items() if k != "ranked"},
    "ranked": [{**r, "hist": r["hist"]} for r in q["ranked"]],
    "pairs": D["pairs"],
    "spec": {"cols": spec["cols"], "bins": spec["bins"], "fmaxHz": spec["fmax_hz"], "peaks": spec["peaks"],
             "noisyPeaks": spec["noisy_peaks"], "survived": spec["survived"],
             "clean": "shazam/spec-clean.png", "noisy": "shazam/spec-noisy.png",
             "values": spec["cols"] * spec["bins"]},
    "hash": D["hash_example"],
    "sweep": D["sweep"],
    "variants": D["variants"],
    "worked": {"tClip": round(t_clip, 2), "tSong": round(t_song, 2), "diff": round(diff, 2)},
    "eq": eq,
    "evidenceSha256": hashlib.sha256(open(os.path.join(EV, "fingerprint.json"), "rb").read()).hexdigest(),
}
os.makedirs(os.path.dirname(OUT_TS), exist_ok=True)
with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* GENERATED by export_shazam_data.py in the reel folder\n"
             " * (books/humanitarians-ai/youtube/week-07/2026-10-09-how-shazam-finds-a-song).\n"
             " * Every point, hash and vote here comes from a real run of fingerprint.py on synthetic\n"
             " * songs (synth.py). Do not hand-edit; re-run the exporter. */\n")
    fh.write("export const SHZ = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"worked pair: clip {t_clip:.2f} s -> song {t_song:.2f} s, offset {diff:.2f} s")
print(f"wrote {OUT_TS} ({os.path.getsize(OUT_TS) / 1024:.0f} KB)")
