"""Exports evidence/scene.json + results.json (written by captions.py) into the Remotion scenes' data module
(scenes/captions/capData.ts), and draws test sentence 1 as an 80-band log-Mel spectrogram (public/captions/mel.png),
computed the way Whisper's front end does: 16 kHz audio, 25 ms windows (400 samples), 10 ms hop (160), 80 Mel bands.

    python export_cap_data.py
"""
import hashlib
import json
import os
import wave

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLKIT = "D:/Rohan/Claude/HAI/RohanClaudeHAIbrutalist.art"
EV = os.path.join(HERE, "evidence")
OUT_TS = os.path.join(TOOLKIT, "runtime/remotion/src/scenes/captions/capData.ts")
PUB = os.path.join(TOOLKIT, "runtime/remotion/public/captions")

S = json.load(open(os.path.join(EV, "scene.json"), encoding="utf-8"))
R = json.load(open(os.path.join(EV, "results.json"), encoding="utf-8"))

with wave.open(os.path.join(EV, "sentence_1.wav")) as w:
    sr = w.getframerate(); y = np.frombuffer(w.readframes(w.getnframes()), "<i2").astype(np.float32) / 32768
from scipy.signal import resample_poly  # noqa: E402
y = resample_poly(y, 16000, sr)
n_fft, hop, n_mels = 400, 160, 80
fr = np.lib.stride_tricks.sliding_window_view(np.pad(y, n_fft // 2), n_fft)[::hop] * np.hanning(n_fft)
P = np.abs(np.fft.rfft(fr, axis=1)) ** 2
f = np.fft.rfftfreq(n_fft, 1 / 16000)
mel = lambda x: 2595 * np.log10(1 + x / 700)
edges = 700 * (10 ** (np.linspace(mel(0), mel(8000), n_mels + 2) / 2595) - 1)
fb = np.zeros((n_mels, len(f)))
for m in range(n_mels):
    lo, c, hi = edges[m], edges[m + 1], edges[m + 2]
    fb[m] = np.clip(np.minimum((f - lo) / (c - lo + 1e-9), (hi - f) / (hi - c + 1e-9)), 0, None)
L = np.log10(np.maximum(P @ fb.T, 1e-10))
L = np.maximum(L, L.max() - 8.0)                       # Whisper clamps to 8 (log10) below the max
g = (L - L.min()) / (L.max() - L.min())
a = np.clip((g - 0.35) / 0.6, 0, 1) * 0.92
rgba = np.zeros((n_mels, g.shape[0], 4), np.uint8)
rgba[..., :3] = (61, 57, 41); rgba[..., 3] = (a.T[::-1] * 255).astype(np.uint8)
os.makedirs(PUB, exist_ok=True)
Image.fromarray(rgba, "RGBA").resize((g.shape[0] * 4, n_mels * 8), Image.BILINEAR).save(os.path.join(PUB, "mel.png"))

clean = R["results"][0]
miss = [d for d in clean["detail"] if d["s"] + d["d"] + d["i"]]
loud = R["results"][-1]
sent1_0db = R["results"][4]["detail"][0]
data = {"example": S["example"], "curve": S["curve"], "mel": {"src": "captions/mel.png", "bands": n_mels, "frames": int(g.shape[0])},
        "clean": {k: clean[k] for k in ("wer", "words", "matched", "med_ms", "p90_ms", "signed_med_ms")},
        "misheard": [{"ref": d["ref"], "hyp": d["hyp"]} for d in miss],
        "loudest": {"snr": loud["snr"], "hyp_words": sum(len(d["hyp"].split()) for d in loud["detail"]), "ref_words": loud["words"],
                    "sample": next(d["hyp"] for d in loud["detail"] if any(d["hyp"].split().count(x) > 3 for x in d["hyp"].split()))},
        "sent1_0db": sent1_0db,
        "voiceCheck": {"name": "Rohan", "price": "$3.50"},
        "evidenceSha256": hashlib.sha256(open(os.path.join(EV, "results.json"), "rb").read()).hexdigest()}
os.makedirs(os.path.dirname(OUT_TS), exist_ok=True)
with open(OUT_TS, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* GENERATED by export_cap_data.py in the reel folder\n"
             " * (books/humanitarians-ai/youtube/week-10/2026-10-30-how-auto-captions-find-each-word).\n"
             " * Every word, time and error rate here comes from a real run of captions.py (faster-whisper base\n"
             " * on sentences built from the narrator's voice). Do not hand-edit; re-run the exporter. */\n")
    fh.write("export const CAP = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"clean WER {clean['wer']}%, misheard {len(miss)}; loudest {data['loudest']['hyp_words']} words for {loud['words']}")
print(f"wrote {OUT_TS} ({os.path.getsize(OUT_TS) / 1024:.0f} KB)")
