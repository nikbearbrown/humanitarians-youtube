"""make_scene_data.py — writes runtime/remotion/src/grokkingData.ts from evidence/grok_toy.json.

The Grokking.tsx scenes import ONLY this file for numbers, so every curve, step count, percentage
and spectrum on screen is the seeded numpy run. The train/held-out mask is rebuilt with the same
seed and permutation grok_toy.py uses (asserted against its train count).
"""
import json
import pathlib

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[3]
d = json.loads((HERE / "grok_toy.json").read_text())
P = d["P"]

rng = np.random.default_rng(d["seed"])
pairs = np.array([(a, b) for a in range(P) for b in range(P)])
perm = rng.permutation(len(pairs))
mask = np.zeros(len(pairs), dtype=int)
mask[perm[: d["train"]]] = 1
assert mask.sum() == d["train"]
mask_str = "".join(map(str, mask))  # row a, column b → index a * P + b

# example cells for B03/B04 (honest: membership read from the mask)
def is_train(a, b):
    return bool(mask[a * P + b])

shown_examples = [(a, b) for a, b in [(60, 50), (12, 40), (88, 23), (7, 95), (45, 61), (30, 30), (71, 52), (19, 84)] if is_train(a, b)][:3]
held_examples = [(a, b) for a, b in [(33, 71), (50, 60), (90, 9), (14, 2), (66, 66), (25, 80), (3, 58), (77, 41)] if not is_train(a, b)][:3]

w, n = d["wd"], d["nowd"]
data = {
    "P": P, "cells": d["cells"], "train": d["train"], "test": d["test"], "trainFrac": d["train_frac"],
    "steps": d["steps"], "seed": d["seed"], "weightDecay": w["wd"],
    "curveWd": w["curve"], "curveNoWd": n["curve"],
    "train100": w["train_100_step"], "testAtTrain100": w["test_at_train_100"],
    "test50": w["test_50_step"], "test99": w["test_99_step"], "gapRatio": w["gap_ratio"],
    "finalTestWd": w["final_test"], "finalTestNoWd": n["final_test"], "finalTrainNoWd": n["final_train"],
    "normStart": w["norm_start"], "normPeakWd": max(c[3] for c in w["curve"]), "normEndWd": w["norm_end"],
    "normEndNoWd": n["norm_end"],
    "fourierWd": w["fourier_energy"], "fourierNoWd": n["fourier_energy"],
    "top5Wd": w["fourier_top5_share"], "top5NoWd": n["fourier_top5_share"], "topKWd": w["fourier_top_k"][:5],
    "mask": mask_str,
    "shownExamples": [[a, b, (a + b) % P] for a, b in shown_examples],
    "heldExamples": [[a, b, (a + b) % P] for a, b in held_examples],
}
# peak weight norm of the wd run, exact, from the every-step log
steps_log = np.load(HERE / "grok_toy_steps.npz")
nrm = steps_log["wd_nrm"]
data["normPeakWd"] = round(float(nrm.max()), 2)
data["normPeakStep"] = int(nrm.argmax()) + 1

out = ROOT / "runtime/remotion/src/grokkingData.ts"
out.write_text(
    "// GENERATED by youtube/brutalist/claude-hai-grokking/evidence/make_scene_data.py from grok_toy.json — do not edit.\n"
    f"export const GK = {json.dumps(data)} as const;\n"
)
summary = {k: v for k, v in data.items() if k not in ("curveWd", "curveNoWd", "mask", "fourierWd", "fourierNoWd")}
print(json.dumps(summary, indent=1))
print("wrote", out)
