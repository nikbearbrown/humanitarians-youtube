"""make_scene_data.py — writes runtime/remotion/src/word2vecData.ts from evidence/w2v_toy.json.

The Word2Vec.tsx scenes import ONLY this file for numbers, so every id, cosine, vector, map position and
ranking on screen is the seeded numpy run (evidence/w2v_toy.py). Nothing here is computed for display
except formatting.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[3]
d = json.loads((HERE / "w2v_toy.json").read_text())

data = {
    "seed": d["seed"], "dim": d["dim"], "window": d["window"], "sentences": d["sentences"], "tokens": d["tokens"],
    "vocab": d["vocab_size"], "ids": d["ids"], "onehot": d["onehot_cos"], "share": d["neighbour_share"],
    "examples": d["examples"], "cos": d["cos"], "offset": d["offset_cos"],
    "mapWords": d["pca_words"], "mapXY": d["pca_xy"], "mapVar2": d["pca_var2"],
    "places": d["group_places"], "people": d["group_people"],
    "kingIncluded": d["analogy_king_included"][:4], "kingExcluded": d["analogy_king_excluded"][:4],
    "kingVector": d["king_vector"], "windowSentence": d["window_sentence"], "tokenVectors": d["token_vectors"],
}
out = ROOT / "runtime/remotion/src/word2vecData.ts"
out.write_text(
    "// GENERATED by youtube/brutalist/claude-hai-word2vec/evidence/make_scene_data.py from w2v_toy.json — do not edit.\n"
    f"export const WV = {json.dumps(data, ensure_ascii=False)} as const;\n"
)
print(json.dumps({k: v for k, v in data.items() if k != "kingVector"}, indent=1, ensure_ascii=False))
print("wrote", out)
