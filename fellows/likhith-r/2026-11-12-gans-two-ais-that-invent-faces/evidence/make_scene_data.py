"""make_scene_data.py — writes runtime/remotion/src/gansData.ts from evidence/gan_toy.json.

Gans.tsx imports ONLY this file for numbers, so the detective-accuracy curve, the forger's histograms
and every percentage / step count on screen come from the seeded numpy run (gan_toy.py).
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[3]
d = json.loads((HERE / "gan_toy.json").read_text())

data = {
    "seed": d["seed"], "steps": d["steps"], "kD": d["k_d"], "mu": d["mu"], "sigma": d["sigma"],
    "accPeak": d["acc_max"], "accPeakStep": d["acc_max_step"], "accFinal": d["acc_final"],
    "accLast500": d["acc_last500_mean"], "accLast500Min": d["acc_last500_min"], "accLast500Max": d["acc_last500_max"],
    "genMean0": d["gen_mean_step0"], "genStd0": d["gen_std_step0"],
    "genMeanFinal": d["gen_mean_final"], "genStdFinal": d["gen_std_final"],
    "curve": d["curve"],  # [step, detective accuracy, forger mean, forger sd]
    "bins": d["bins"], "hists": d["hists"], "realHist": d["real_hist"], "snapSteps": sorted(int(k) for k in d["hists"]),
}
out = ROOT / "runtime/remotion/src/gansData.ts"
out.write_text(
    "// GENERATED by youtube/brutalist/claude-hai-gans/evidence/make_scene_data.py from gan_toy.json — do not edit.\n"
    f"export const GN = {json.dumps(data)} as const;\n"
)
print(json.dumps({k: v for k, v in data.items() if k not in ("curve", "bins", "hists", "realHist")}, indent=1))
print("wrote", out)
